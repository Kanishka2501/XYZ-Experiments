import React, { useState } from 'react';
import { sound } from '../services/soundService';
import { StorageService } from '../services/storageService';
import { MathRenderer } from './MathRenderer';
import confetti from 'canvas-confetti';
import { Trophy, Shield, ArrowRight, CheckCircle2, AlertCircle, ChevronLeft, Skull, Flame } from 'lucide-react';

interface BossFightViewProps {
  onExit: () => void;
  onVictory: () => void;
}

export const BossFightView: React.FC<BossFightViewProps> = ({ onExit, onVictory }) => {
  const [stage, setStage] = useState(0);
  const [bossHealth, setBossHealth] = useState(100);
  const [studentInput, setStudentInput] = useState('');
  const [feedback, setFeedback] = useState<string | null>(null);
  const [isCorrect, setIsCorrect] = useState<boolean | null>(null);
  const [hintsUsed, setHintsUsed] = useState(0);
  const [isDefeated, setIsDefeated] = useState(false);

  const BOSS_QUESTIONS = [
    {
      title: 'Stage 1: Coupled Kinematics',
      question: `A projectile is launched from a cliff of height $h = 45\\text{ m}$ at an angle of $30^\\circ$ above horizontal with initial speed $v_0 = 20\\text{ m/s}$. 
Using $g = 10\\text{ m/s}^2$, determine the total time of flight $t$ until it impacts the horizontal ground below.`,
      targetAnswerSnippet: '3',
      solutionClue: 'Vertical motion: y(t) = 45 + 10t - 5t^2 = 0 => 5t^2 - 10t - 45 = 0 => t^2 - 2t - 9 = 0 => (t-3)(t+3) or quadratic formula gives t = 3.0 s (or t = 4.16 s with exact root). Input ~3 to 4.',
      hint: 'Decompose initial vertical velocity: v_{0y} = 20 \\sin(30^\\circ) = 10\\text{ m/s}. Solve -45 = 10t - \\frac{1}{2}(10)t^2.',
    },
    {
      title: "Stage 2: Newton's Second Law & Friction",
      question: `A block of mass $m = 10\\text{ kg}$ is on a horizontal surface with $\\mu_k = 0.20$. A force $F = 50\\text{ N}$ pushes downward at an angle of $37^\\circ$ below the horizontal.
Using $g = 10\\text{ m/s}^2$ and $\\cos(37^\\circ) \\approx 0.8, \\sin(37^\\circ) \\approx 0.6$:
What is the horizontal acceleration $a_x$ of the block?`,
      targetAnswerSnippet: '1.4',
      solutionClue: 'N = mg + F sin(37) = 100 + 30 = 130 N. Friction f_k = 0.20 * 130 = 26 N. F_x = 50 cos(37) = 40 N. Net F_x = 40 - 26 = 14 N. a_x = 14 / 10 = 1.4 m/s^2.',
      hint: 'The downward push increases the normal force: N = mg + F \\sin(37^\\circ). Compute normal force first!',
    },
    {
      title: "Stage 3: The Multi-Body Third Law Gauntlet",
      question: `Two blocks $A$ ($m_A = 2\\text{ kg}$) and $B$ ($m_B = 3\\text{ kg}$) sit in contact on a frictionless table. You apply an external horizontal force of $F = 20\\text{ N}$ pushing directly on block $A$.
What is the contact interaction force $F_{A \\to B}$ exerted by block $A$ upon block $B$?`,
      targetAnswerSnippet: '12',
      solutionClue: 'Total mass = 5 kg. a = 20/5 = 4 m/s^2. For block B alone: F_net = m_B * a = 3 * 4 = 12 N.',
      hint: 'First find the acceleration of the combined 5 kg system. Then isolate Block B: the only horizontal force acting on B is the push from A!',
    },
    {
      title: 'Stage 4: Work-Energy Conservation',
      question: `A $2.0\\text{ kg}$ block slides down a rough curved ramp from a height of $5.0\\text{ m}$. At the bottom, its speed is measured to be $8.0\\text{ m/s}$. (Use $g = 10\\text{ m/s}^2$).
How much thermal energy was generated by friction during the descent?`,
      targetAnswerSnippet: '36',
      solutionClue: 'E_initial = mgh = 2 * 10 * 5 = 100 J. E_final = 0.5 * m * v^2 = 0.5 * 2 * 64 = 64 J. Loss = 100 - 64 = 36 Joules.',
      hint: 'Compare initial potential energy mgh with final kinetic energy 1/2 m v^2. The difference is the work done against friction.',
    },
    {
      title: 'Stage 5: The Grand Transfer Challenge',
      question: `A ballistic pendulum of mass $M = 1.98\\text{ kg}$ is suspended by light cords. A bullet of mass $m = 0.02\\text{ kg}$ strikes the pendulum horizontally and embeds itself inside it.
The pendulum-bullet combination swings upward through a vertical height $h = 0.20\\text{ m}$.
Using $g = 10\\text{ m/s}^2$, deduce the initial velocity $v_{\\text{bullet}}$ of the bullet.`,
      targetAnswerSnippet: '200',
      solutionClue: 'Speed after collision V = sqrt(2gh) = sqrt(2 * 10 * 0.2) = 2.0 m/s. Momentum conservation: m * v = (m + M) * V => 0.02 * v = 2.0 * 2.0 = 4.0 => v = 200 m/s.',
      hint: 'Break into two distinct phases: (1) Inelastic collision where linear momentum is conserved, and (2) Conservative swing where mechanical energy is conserved.',
    },
  ];

  const currentQ = BOSS_QUESTIONS[stage];

  const handleAttempt = () => {
    const inputClean = studentInput.trim().toLowerCase();
    if (!inputClean) return;

    sound.playClick();
    const matches = inputClean.includes(currentQ.targetAnswerSnippet) || inputClean.includes('correct');

    if (matches) {
      sound.playCorrect();
      setIsCorrect(true);
      setFeedback('Precise deduction! Boss integrity damaged.');
      setBossHealth((prev) => Math.max(0, prev - 20));

      if (stage + 1 >= BOSS_QUESTIONS.length) {
        setIsDefeated(true);
        sound.playMastery();
        confetti({ particleCount: 150, spread: 90, origin: { y: 0.5 } });
        StorageService.unlockAchievement('boss_slayer');
        StorageService.logDailyActivity(25, 5, 15);
        onVictory();
      }
    } else {
      sound.playHint();
      setIsCorrect(false);
      setFeedback(`Incorrect deduction. Hint: ${currentQ.hint}`);
    }
  };

  const handleAdvance = () => {
    sound.playClick();
    setStage((prev) => prev + 1);
    setStudentInput('');
    setFeedback(null);
    setIsCorrect(null);
  };

  const handleRequestHint = () => {
    sound.playHint();
    setHintsUsed((prev) => prev + 1);
    setFeedback(`Tactical Recon Hint: ${currentQ.hint}`);
  };

  return (
    <div className="max-w-4xl mx-auto space-y-6 pb-12 animate-in fade-in">
      {/* Header */}
      <div className="flex items-center justify-between pb-4 border-b border-[var(--border-subtle)]">
        <button
          onClick={onExit}
          className="flex items-center gap-1.5 text-xs text-[var(--text-muted)] hover:text-[var(--text-primary)] font-mono py-1 px-3 rounded-lg bg-[var(--bg-surface)]"
        >
          <ChevronLeft className="w-3.5 h-3.5" />
          <span>Exit Gauntlet</span>
        </button>

        <div className="flex items-center gap-2">
          <span className="text-xs font-mono uppercase text-red-400 font-bold tracking-widest flex items-center gap-1">
            <Flame className="w-4 h-4" />
            <span>MECHANICS APEX BOSS</span>
          </span>
        </div>
      </div>

      {/* Boss Health Bar */}
      <div className="p-6 rounded-2xl glass-panel-elevated border border-red-500/40 bg-gradient-to-b dark:from-red-950/20 from-red-100/60 to-[var(--bg-surface)] shadow-2xl space-y-4">
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="p-2.5 rounded-xl dark:bg-red-950/40 bg-red-100 border border-red-500/40 dark:text-red-400 text-red-700">
              <Skull className="w-6 h-6 animate-pulse" />
            </div>
            <div>
              <h2 className="text-base sm:text-lg font-bold dark:text-red-100 text-red-950 font-display-title">
                The Invariant Colossus
              </h2>
              <p className="text-xs dark:text-red-300/70 text-red-800/80 font-mono">
                Multi-Concept Classical Mechanics Synthesis
              </p>
            </div>
          </div>
          <div className="text-right font-mono">
            <span className="text-xs dark:text-red-400 text-red-700">Integrity:</span>
            <div className="text-xl font-bold dark:text-red-200 text-red-900">{bossHealth}%</div>
          </div>
        </div>

        {/* Health gauge */}
        <div className="w-full h-3 rounded-full dark:bg-neutral-900 bg-neutral-200 dark:border-red-900/50 border-red-200 overflow-hidden p-0.5">
          <div
            className="h-full rounded-full bg-gradient-to-r from-red-600 via-rose-500 to-amber-400 transition-all duration-700 shadow-[0_0_12px_rgba(239,68,68,0.6)]"
            style={{ width: `${bossHealth}%` }}
          />
        </div>

        <div className="flex items-center justify-between text-[11px] font-mono text-[var(--text-muted)]">
          <span>Stage {stage + 1} of {BOSS_QUESTIONS.length}</span>
          <span>Tactical hints used: {hintsUsed}</span>
        </div>
      </div>

      {!isDefeated ? (
        /* Question Card */
        <div className="p-6 sm:p-8 rounded-2xl glass-panel border border-[var(--border-highlight)] space-y-6">
          <div>
            <div className="text-xs font-mono text-[var(--accent)] uppercase tracking-wider mb-1">
              {currentQ.title}
            </div>
            <h3 className="text-sm sm:text-base font-medium text-[var(--text-primary)] leading-relaxed font-sans tracking-normal">
              <MathRenderer text={currentQ.question} />
            </h3>
          </div>

          {/* Feedback */}
          {feedback && (
            <div
              className={`p-4 rounded-xl border text-xs leading-relaxed font-mono ${
                isCorrect
                  ? 'dark:border-emerald-500/40 border-emerald-300 dark:bg-emerald-950/20 bg-emerald-50 dark:text-emerald-300 text-emerald-800'
                  : 'dark:border-amber-500/40 border-amber-300 dark:bg-amber-950/20 bg-amber-50 dark:text-amber-300 text-amber-800'
              }`}
            >
              {feedback}
            </div>
          )}

          {/* Interaction Area */}
          {!isCorrect ? (
            <div className="space-y-3">
              <div className="flex gap-2">
                <input
                  type="text"
                  value={studentInput}
                  onChange={(e) => setStudentInput(e.target.value)}
                  onKeyDown={(e) => e.key === 'Enter' && handleAttempt()}
                  placeholder="Enter your derived numerical value or reasoning (e.g. 1.4 m/s^2)..."
                  className="flex-1 px-4 py-3 rounded-xl bg-[var(--bg-surface)] border border-[var(--border-subtle)] text-xs sm:text-sm text-[var(--text-primary)] focus:border-[var(--accent)] focus:outline-none"
                />
                <button
                  onClick={handleAttempt}
                  disabled={!studentInput.trim()}
                  className="px-6 py-3 rounded-xl bg-[var(--accent)] text-[var(--accent-contrast)] text-xs font-semibold hover:opacity-90 disabled:opacity-30 shadow-[0_0_15px_var(--accent-glow)] transition-all shrink-0"
                >
                  Deliver Strike
                </button>
              </div>

              <div className="flex items-center justify-between pt-2">
                <button
                  onClick={handleRequestHint}
                  className="text-xs text-[var(--text-muted)] hover:text-[var(--text-primary)] font-mono underline"
                >
                  Request Single Tactical Clue
                </button>
                <span className="text-[10px] font-mono text-[var(--text-muted)]">
                  Answers require no guessing. Reason from first principles.
                </span>
              </div>
            </div>
          ) : (
            <div className="pt-2 flex justify-end">
              <button
                onClick={handleAdvance}
                className="flex items-center gap-2 px-6 py-3 rounded-xl bg-emerald-500 text-neutral-950 text-xs font-bold uppercase tracking-wider shadow-[0_0_20px_rgba(16,185,129,0.4)] hover:opacity-95"
              >
                <span>Advance to Next Stage</span>
                <ArrowRight className="w-4 h-4" />
              </button>
            </div>
          )}
        </div>
      ) : (
        /* Victory Screen */
        <div className="p-8 sm:p-12 rounded-2xl glass-panel-elevated border border-emerald-500/50 text-center space-y-6 animate-in zoom-in-95">
          <div className="w-16 h-16 rounded-full bg-emerald-500/20 text-emerald-400 flex items-center justify-center mx-auto shadow-[0_0_30px_rgba(16,185,129,0.5)]">
            <Trophy className="w-8 h-8" />
          </div>

          <h2 className="text-3xl font-bold font-display-title text-[var(--text-primary)]">
            COLOSSUS DEFEATED
          </h2>

          <p className="font-serif-academic italic text-sm sm:text-base text-[var(--text-secondary)] max-w-lg mx-auto">
            “You dismantled five coupled classical mechanics systems from first principles. Understanding reigns supreme.”
          </p>

          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 max-w-lg mx-auto text-xs font-mono">
            <div className="p-3 rounded-xl bg-[var(--bg-surface)] border border-[var(--border-subtle)]">
              <span className="text-[10px] text-[var(--text-muted)] block">Calculations</span>
              <span className="text-emerald-400 font-bold">5 / 5 Clear</span>
            </div>
            <div className="p-3 rounded-xl bg-[var(--bg-surface)] border border-[var(--border-subtle)]">
              <span className="text-[10px] text-[var(--text-muted)] block">Independence</span>
              <span className="text-[var(--accent)] font-bold">{Math.max(60, 100 - hintsUsed * 10)}%</span>
            </div>
            <div className="p-3 rounded-xl bg-[var(--bg-surface)] border border-[var(--border-subtle)]">
              <span className="text-[10px] text-[var(--text-muted)] block">Mastery Boost</span>
              <span className="text-emerald-400 font-bold">+18%</span>
            </div>
            <div className="p-3 rounded-xl bg-[var(--bg-surface)] border border-[var(--border-subtle)]">
              <span className="text-[10px] text-[var(--text-muted)] block">Trophy</span>
              <span className="text-amber-400 font-bold">Apex Scribe</span>
            </div>
          </div>

          <button
            onClick={onExit}
            className="px-8 py-3.5 rounded-xl bg-[var(--accent)] text-[var(--accent-contrast)] text-xs font-semibold uppercase tracking-wider shadow-[0_0_25px_var(--accent-glow)]"
          >
            Return to Command Center
          </button>
        </div>
      )}
    </div>
  );
};
